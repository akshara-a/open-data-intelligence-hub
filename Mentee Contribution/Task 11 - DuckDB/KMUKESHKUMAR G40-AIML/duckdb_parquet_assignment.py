"""### 2. Display the top three highest-paid employees."""

top_three_highest_paid_employees = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
    ORDER BY salary DESC
    LIMIT 3
""").df()

print(top_three_highest_paid_employees)

"""### 3. Calculate the average salary for each city."""

avg_salary_by_city = duckdb.sql("""
    SELECT
        city,
        AVG(salary) AS average_salary
    FROM read_parquet('employees.parquet')
    GROUP BY city
    ORDER BY average_salary DESC
""").df()

print(avg_salary_by_city)

"""### 4. Find departments with an average salary greater than `55000`."""

departments_high_avg_salary = duckdb.sql("""
    SELECT
        department,
        AVG(salary) AS average_salary
    FROM read_parquet('employees.parquet')
    GROUP BY department
    HAVING AVG(salary) > 55000
    ORDER BY average_salary DESC
""").df()

print(departments_high_avg_salary)

"""### 5. Add a calculated column named `salary_category`"""

salary_category_employees = duckdb.sql("""
    SELECT
        name,
        salary,
        CASE
            WHEN salary >= 65000 THEN 'High'
            WHEN salary >= 50000 THEN 'Medium'
            ELSE 'Low'
        END AS salary_category
    FROM read_parquet('employees.parquet')
    ORDER BY salary DESC
""").df()

print(salary_category_employees)