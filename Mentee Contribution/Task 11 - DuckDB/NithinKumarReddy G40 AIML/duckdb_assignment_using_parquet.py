# Task 2: Read Parquet Using DuckDB
# ==============================================================================
print("--- Task 2: Read Parquet File ---")
all_employees = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
""").df()
print(all_employees)
print("\n")


# ==============================================================================
# Task 3: Filter Employee Records
# ==============================================================================
print("--- Task 3: Filter Employee Records ---")

# 1. Salary > 50000
high_salary = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
    WHERE salary > 50000
""").df()
print("1. Salary > 50000:\n", high_salary)

# 2. IT Department
it_dept = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
    WHERE department = 'IT'
""").df()
print("\n2. IT Department:\n", it_dept)

# 3. Work in Delhi
delhi_employees = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
    WHERE city = 'Delhi'
""").df()
print("\n3. Employees in Delhi:\n", delhi_employees)

# 4. IT Department with Salary > 65000
it_high_salary = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
    WHERE department = 'IT' AND salary > 65000
""").df()
print("\n4. IT Department & Salary > 65000:\n", it_high_salary)
print("\n")


# ==============================================================================
# Task 4: Select Specific Columns & Sort
# ==============================================================================
print("--- Task 4: Select Specific Columns & Sort ---")
sorted_employees = duckdb.sql("""
    SELECT name, department, salary
    FROM read_parquet('employees.parquet')
    ORDER BY salary DESC
""").df()
print(sorted_employees)
print("\n")


# ==============================================================================
# Task 5: Perform Aggregations
# ==============================================================================
print("--- Task 5: Aggregate Calculations ---")
aggregations = duckdb.sql("""
    SELECT
        COUNT(*) AS total_employees,
        AVG(salary) AS average_salary,
        MAX(salary) AS maximum_salary,
        MIN(salary) AS minimum_salary,
        SUM(salary) AS total_salary
    FROM read_parquet('employees.parquet')
""").df()
print(aggregations)
print("\n")


# ==============================================================================
# Task 6: Group Data by Department
# ==============================================================================
print("--- Task 6: Group Data by Department ---")
dept_summary = duckdb.sql("""
    SELECT
        department,
        COUNT(*) AS employee_count,
        AVG(salary) AS average_salary,
        MAX(salary) AS highest_salary,
        SUM(salary) AS total_salary
    FROM read_parquet('employees.parquet')
    GROUP BY department
    ORDER BY average_salary DESC
""").df()
print(dept_summary)
print("\n")


# ==============================================================================
# Task 7: Create a DuckDB Table & Database File
# ==============================================================================
print("--- Task 7: Persistent DuckDB Database Table ---")
connection = duckdb.connect("company.duckdb")

connection.execute("""
    CREATE OR REPLACE TABLE employees AS
    SELECT *
    FROM read_parquet('employees.parquet')
""")

table_data = connection.execute("SELECT * FROM employees").df()
print("Data read from 'company.duckdb':\n", table_data)
connection.close()
print("\n")


# ==============================================================================
# Task 8: Export Query Results to Parquet
