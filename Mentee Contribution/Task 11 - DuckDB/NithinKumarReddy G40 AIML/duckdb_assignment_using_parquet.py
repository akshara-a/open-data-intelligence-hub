print("--- Bonus Tasks ---")

# Bonus 1: Employee with the second-highest salary
second_highest = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
    ORDER BY salary DESC
    LIMIT 1 OFFSET 1
""").df()
print("1. Second-highest salary employee:\n", second_highest)

# Bonus 2: Top three highest-paid employees
top_three = duckdb.sql("""
    SELECT *
    FROM read_parquet('employees.parquet')
    ORDER BY salary DESC
    LIMIT 3
""").df()
print("\n2. Top 3 highest-paid employees:\n", top_three)

# Bonus 3: Average salary for each city
city_avg_salary = duckdb.sql("""
    SELECT city, AVG(salary) AS average_salary
    FROM read_parquet('employees.parquet')
    GROUP BY city
    ORDER BY average_salary DESC
""").df()
print("\n3. Average salary by city:\n", city_avg_salary)

# Bonus 4: Departments with average salary > 55000
dept_above_55k = duckdb.sql("""
    SELECT department, AVG(salary) AS average_salary
    FROM read_parquet('employees.parquet')
    GROUP BY department
    HAVING AVG(salary) > 55000
""").df()
print("\n4. Departments with average salary > 55000:\n", dept_above_55k)

# Bonus 5: Calculated column salary_category
salary_categories = duckdb.sql("""
    SELECT
        name,
        salary,
        CASE
            WHEN salary >= 65000 THEN 'High'
            WHEN salary >= 50000 THEN 'Medium'
            ELSE 'Low'
        END AS salary_category
    FROM read_parquet('employees.parquet')
""").df()
print("\n5. Salary Categories:\n", salary_categories)